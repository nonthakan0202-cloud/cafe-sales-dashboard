import pandas as pd

# 1. โหลดข้อมูลดิบจากไฟล์ CSV
df = pd.read_csv('raw_cafe_sales.csv')
print('--- ข้อมูลดิบเริ่มต้น (ก่อนคลีน) ---')
print(f'จำนวนแถวทั้งหมด: {len(df)} แถว\n')

# 2. ลบข้อมูลที่ซ้ำกัน (Duplicate Rows)
df = df.drop_duplicates()

# 3. จัดรูปแบบข้อความ (Text Standardization)
# ตัดช่องว่างส่วนเกินหน้า/หลังข้อความ
text_columns = ['รหัสคำสั่งซื้อ', 'สาขา', 'หมวดหมู่', 'ชื่อเมนู', 'ช่องทางชำระเงิน', 'สถานะ']
for col in text_columns:
    if col in df.columns:
        df[col] = df[col].astype(str).str.strip()

# แก้ไขคำที่สะกดผิดหรือใช้คำต่างกันให้เป็นมาตรฐานเดียว
df['ชื่อเมนู'] = df['ชื่อเมนู'].replace({'อเมริกาโนเย็น': 'อเมริกาโน่เย็น'})
df['ช่องทางชำระเงิน'] = df['ช่องทางชำระเงิน'].replace({'สด': 'เงินสด'})

# 4. จัดการค่าว่าง (Missing Values)
# แปลงคอลัมน์ตัวเลขให้เป็น float/int เพื่อป้องกัน Error
df['ราคาต่อหน่วย'] = pd.to_numeric(df['ราคาต่อหน่วย'], errors='coerce')
df['จำนวน'] = pd.to_numeric(df['จำนวน'], errors='coerce')

# เติมราคาต่อหน่วยที่หายไป (เช่น ลาเต้เย็น ราคา 75 บาท)
df.loc[(df['ชื่อเมนู'] == 'ลาเต้เย็น') & (df['ราคาต่อหน่วย'].isnull()), 'ราคาต่อหน่วย'] = 75

# เติมช่องทางชำระเงินที่ว่างด้วย 'ไม่ระบุ'
df['ช่องทางชำระเงิน'] = df['ช่องทางชำระเงิน'].fillna('ไม่ระบุ')

# 5. ปรับรูปแบบวันที่ให้เป็นมาตรฐานเดียวกัน (YYYY-MM-DD)
df['วันที่'] = pd.to_datetime(df['วันที่'], format='mixed').dt.strftime('%Y-%m-%d')

# 6. กรองข้อมูลผิดปกติและคำนวณยอดขาย
# ตัดรายการที่สถานะเป็น 'ยกเลิก' หรือจำนวนติดลบ/ศูนย์ออก
df = df[(df['สถานะ'] == 'สำเร็จ') & (df['จำนวน'] > 0)]

# สร้างคอลัมน์ใหม่ 'ยอดรวม' (จำนวน * ราคาต่อหน่วย)
df['ยอดรวม'] = df['จำนวน'] * df['ราคาต่อหน่วย']

# 7. บันทึกไฟล์ข้อมูลที่สะอาดแล้ว (ใช้ encoding='utf-8-sig' เพื่อให้อ่านภาษาไทยใน Excel ได้ถูกต้อง)
df.to_csv('clean_cafe_sales.csv', index=False, encoding='utf-8-sig')

print('--- ทำความสะอาดข้อมูลสำเร็จ! ---')
print(f'จำนวนแถวหลังคลีนและกรองข้อมูล:  {len(df)} แถว')
print(df.head(10))